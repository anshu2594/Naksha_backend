class Command(BaseCommand):
    help = "Create or update Naksha's catalog from the existing React product data."

    def handle(self, *args, **options):
        for category in CATEGORIES:
            Category.objects.update_or_create(id=category["id"], defaults=category)
        for product in PRODUCTS:
            Product.objects.update_or_create(id=product["id"], defaults=product)
        self.stdout.write(
            self.style.SUCCESS(
                f"Catalog ready: {len(CATEGORIES)} categories, {len(PRODUCTS)} products."
            )
        )
